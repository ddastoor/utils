// Shared by scripts/make-graphviz-reference.mjs (native dot → tests/fixtures/graphviz/reference.json) and the suites
// that hold our module to it (tests/unit/graphviz.test.mjs): how a fixture is cut into graphs, what of an output is
// compared, and the "signature" of a drawing — everything about it that does not depend on where things were put.
import { createHash } from 'node:crypto';

export const ENGINES = ['dot', 'neato', 'fdp', 'sfdp', 'circo', 'twopi', 'osage', 'patchwork'];
/** Engines whose drawings are the same on every machine (integer or sorted work; fdp, sfdp and twopi run
 *  through sin / cos / pow, whose last digit differs between C libraries and then grows over the iterations). */
export const EXACT = ['dot', 'neato', 'circo', 'osage', 'patchwork'];
export const short = (text) => createHash('sha256').update(text).digest('hex').slice(0, 12);
/** An SVG without the line that names the build. */
export const normSvg = (svg) => svg.replace(/<!-- Generated by graphviz version [^\n]*\n/, '').replace(/\r\n/g, '\n');

/** A hazard file is cut at the lines that start with four slashes (comments to Graphviz): one graph a piece.
 *  `line` = lines of the file in front of the piece (Graphviz counts the lines of every graph from 1). */
export function sections(text) {
  const out = []; let cur = null, n = 0;
  for (const l of text.split('\n')) {
    if (l.startsWith('////')) { cur = { title: l.slice(4).trim(), lines: [], line: n + 1 }; out.push(cur); }
    else if (cur) cur.lines.push(l);
    n++;
  }
  return out.map((s, i) => ({ title: s.title || out.slice(0, i).reverse().find((p) => p.title)?.title || '', text: s.lines.join('\n'), line: s.line }));
}
/** The words of a line of the plain format (names and labels may be quoted, with \" inside). */
export function plainWords(line) {
  const w = []; const re = /"((?:[^"\\]|\\.)*)"|(\S+)/g; let m;
  while ((m = re.exec(line))) w.push(m[1] !== undefined ? m[1].replace(/\\(.)/g, '$1') : m[2]);
  return w;
}
/** Graphs of a plain output (one per "graph … stop" block): nodes and edges without their coordinates.
 *  node name x y width height label style shape color fillcolor
 *  edge tail head n x1 y1 … xn yn [label xl yl] style color */
export function plainGraphs(plain) {
  const graphs = []; let g = null;
  for (const l of plain.split('\n')) {
    if (l.startsWith('graph ')) { g = { nodes: [], edges: [] }; graphs.push(g); }
    else if (l.startsWith('node ') && g) { const w = plainWords(l); g.nodes.push([w[1], w[4], w[5], ...w.slice(6)].join('\u0001')); }
    else if (l.startsWith('edge ') && g) { const w = plainWords(l), n = +w[3], rest = w.slice(4 + 2 * n); g.edges.push([w[1], w[2], ...(rest.length > 2 ? [rest[0], ...rest.slice(3)] : rest)].join('\u0001')); }
  }
  return graphs;
}
/** What a drawing is, apart from positions: which nodes (name, size, label, style, shape, colours) and which edges.
 *  Characters outside ASCII count as "something": the tool prints the names of a Latin-1 file in the file's bytes,
 *  the module — which is handed text — in UTF-8. (Where the SVGs are the same nobody needs this.) */
export function signature(g) { return short(([...g.nodes].sort().join('\n') + '\n--\n' + [...g.edges].sort().join('\n')).replace(/[^\x00-\x7f]+/g, '?')); }
/** The SVG documents in what `dot -Tsvg` wrote for a file with several graphs. */
export const splitSvgs = (out) => out.split(/(?=<\?xml )/).filter((s) => s.trim());
/** Graphviz's messages without what differs between the tool and the module: the file's name in a syntax error,
 *  and empty lines. */
export function normErr(text, file = '') {
  return text.split('\n').map((l) => (file ? l.split(`${file}: `).join('') : l).replace(/^(Error|Warning): <stdin>: /, '$1: ')
    .replace(/^\S*dot_static: \S*\/(lib\/\S+)/, 'dot: $1').trimEnd()).filter(Boolean).join('\n');   // a failed assertion names the build directory
}
/** Did the native tool end by a signal (a failed assertion aborts it)? */
export const aborted = (entry) => /^signal /.test(String(entry?.rc ?? ''));
