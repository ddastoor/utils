// Linux Terminal runtime: our shell + WASI host + in-memory FS running the real busybox.wasm (Node).
// Part 1: shell language features. (Every BusyBox applet is covered in terminal-applets.test.mjs.)
import { readFileSync } from 'node:fs';
export default async (t, { load, root }) => {
  const { bootSystem } = await load('/src/lib/terminal/system.ts');
  const mod = await WebAssembly.compile(readFileSync(`${root}/src/wasm/bin/busybox.wasm`));
  const sh = bootSystem(mod, { out: () => {}, err: () => {} });
  const r = (cmd) => sh.capture(cmd);
  const eq = (cmd, want, msg) => { const x = r(cmd); t.eq(x.out, want, `${msg || cmd}${x.err ? ` [stderr: ${x.err.trim()}]` : ''}`); };
  eq('echo hello', 'hello\n');
  eq('pwd', '/home/user\n', 'starts in /home/user');
  eq("echo 'single $HOME' \"double $HOME\" esc\\ aped", 'single $HOME double /home/user esc aped\n', 'quoting');
  eq('X=5; echo $X ${X} ${Y:-dflt} ${X:+set}', '5 5 dflt set\n', 'variables + default/alt');
  eq('echo $((2**10 + 7 % 4 * 3)) $(( (1<2) && (3>2) ))', '1033 1\n', 'arithmetic');
  eq('echo "files: $(echo a b | wc -w)"', 'files: 2\n', 'command substitution');
  eq('echo `echo back`ticks', 'backticks\n');
  eq('printf "b\\na\\nc\\n" | sort | head -n 2', 'a\nb\n', 'pipeline');
  eq('yes | head -n 3', 'y\ny\ny\n', 'infinite producer stopped by the output cap (SIGPIPE stand-in)');
  eq('false && echo no || echo yes', 'yes\n', '&& ||');
  eq('true; echo $?; false; echo $?', '0\n1\n', '$?');
  eq('echo one > f.txt; echo two >> f.txt; cat < f.txt', 'one\ntwo\n', '> >> <');
  eq('ls nope 2>&1 | wc -l', '1\n', '2>&1 into a pipe');
  eq('ls nope 2>/dev/null; echo rc=$?', 'rc=1\n', '2>/dev/null');
  eq('cat <<EOF\nhi $USER\n$((6*7))\nEOF', 'hi user\n42\n', 'here-doc with expansion');
  eq("cat <<'EOF'\nraw $USER\nEOF", 'raw $USER\n', 'quoted here-doc');
  eq('wc -c <<< "abc"', '4\n', 'here-string');
  eq('mkdir -p d/e && touch d/a.txt d/b.txt d/c.md && echo d/*.txt', 'd/a.txt d/b.txt\n', 'globbing');
  eq('echo d/[ab].txt d/?.md', 'd/a.txt d/b.txt d/c.md\n', 'glob classes and ?');
  eq('echo "d/*.txt"', 'd/*.txt\n', 'quoted glob not expanded');
  eq('echo nomatch*', 'nomatch*\n', 'unmatched glob stays literal');
  eq('for f in d/*.txt; do echo "<$f>"; done', '<d/a.txt>\n<d/b.txt>\n', 'for loop');
  eq('i=0; while [ $i -lt 3 ]; do i=$((i+1)); echo $i; done', '1\n2\n3\n', 'while loop');
  eq('n=3; until [ $n -eq 0 ]; do echo $n; n=$((n-1)); done', '3\n2\n1\n', 'until loop');
  eq('if [ -d d ]; then echo dir; elif true; then echo no; else echo no; fi', 'dir\n', 'if/elif/else');
  eq('for i in 1 2 3 4; do [ $i = 3 ] && break; echo $i; done', '1\n2\n', 'break');
  eq('{ echo a; echo b; } | wc -l', '2\n', '{ group } into pipe');
  eq('(cd /tmp; pwd); pwd', '/tmp\n/home/user\n', '( subshell ) keeps cwd');
  eq('cd d && pwd && cd .. && pwd', '/home/user/d\n/home/user\n', 'cd');
  eq('cd /nowhere', '', 'cd error is on stderr');
  eq('export FOO=bar; awk \'BEGIN{print ENVIRON["FOO"]}\'', 'bar\n', 'export reaches applets');
  eq('A=1 awk \'BEGIN{print ENVIRON["A"]}\'; awk \'BEGIN{print ENVIRON["A"] "-"}\'', '1\n-\n', 'VAR=x prefix for one command only');
  eq('B=2; awk \'BEGIN{print ENVIRON["B"] "-"}\'', '-\n', 'unexported variable stays in the shell');
  eq('printf "x y\\n" | { read a b; echo "$b-$a"; }', 'y-x\n', 'read');
  eq('printf "1\\n2\\n" > n.txt; while read l; do echo "[$l]"; done < n.txt', '[1]\n[2]\n', 'while read < file');
  eq('which ls cd', '/bin/ls\ncd: shell builtin\n', 'which');
  eq('ls /bin | grep -c .', `${sh.applets.size + 1}\n`, '/bin has every applet');
  eq('/bin/echo full path', 'full path\n');
  eq('busybox echo via busybox', 'via busybox\n');
  eq('echo "echo from script; echo arg=\\$1" > s.sh; sh s.sh', 'from script\narg=\n', 'sh script.sh');
  eq('sh -c "echo inner"', 'inner\n');
  eq('nosuchcmd 2>&1; echo $?', 'sh: nosuchcmd: command not found\n127\n', 'command not found → 127');
  eq('echo ~ ~/x', '/home/user /home/user/x\n', 'tilde');
  eq('# comment only', '', 'comment');
  eq('echo a # trailing comment', 'a\n');
  t.ok(r('if then').err.includes('syntax error'), 'syntax errors reported');
  eq('history | tail -n 1 | grep -c history', '0\n', 'capture() does not record history');
  sh.run('echo recorded > /dev/null');
  t.ok(sh.history.includes('echo recorded > /dev/null'), 'run() records history');
  // tar compression handled by the shell (BusyBox would fork a compressor)
  eq('printf "hello\\n" > h.txt; tar -czf h.tgz h.txt && tar -tzf h.tgz', 'h.txt\n', 'tar -czf / -tzf');
  eq('mkdir x && cd x && tar -xzf ../h.tgz && cat h.txt; cd ..', 'hello\n', 'tar -xzf');
  eq('tar cjf h.tbz2 h.txt && tar tf h.tbz2', 'h.txt\n', 'tar cjf (old-style flags) + auto-detect on list');
  eq('tar -cf - h.txt | tar -tf -', 'h.txt\n', 'tar through a pipe');
  t.ok(r('tar -cJf h.txz h.txt').err.includes('not supported'), 'tar -J create explains xz has no compressor');
  // limits and safety
  const big = r('yes 0123456789 | head -c 200000 | wc -c');
  t.eq(big.out, '200000\n', 'large pipelines');
  t.ok(r('echo $((1/0))').err.includes('division by zero'), 'arith division by zero');
};
