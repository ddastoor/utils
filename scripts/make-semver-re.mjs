// Writes wasm/devcore/src/semver_re.rs: the regular expressions of npm's `semver` package (node_modules/semver/internal/re.js,
// ISC licence), exactly as that package builds them ("safe" forms with bounded repeats), for our Rust port of its range
// logic (wasm/devcore/src/semver_npm.rs).   Run: node scripts/make-semver-re.mjs   (after `npm ci`)
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
const { safeSrc, src, t } = require('semver/internal/re');
const { version } = require('semver/package.json');
const names = ['FULL', 'XRANGE', 'TILDE', 'CARET', 'COMPARATOR', 'TILDETRIM', 'CARETTRIM', 'HYPHENRANGE', 'STAR', 'GTE0', 'GTE0PRE', 'BUILD', 'PRERELEASE'];
let out = `//! Generated by scripts/make-semver-re.mjs from npm semver ${version} (internal/re.js, ISC licence) — do not edit.\n`;
for (const n of names) out += `pub const ${n}: &str = r#"${safeSrc[t[n]]}"#;\n`;
out += `/// build metadata, unbounded (range.js BUILDSTRIPRE)\npub const BUILDSTRIP: &str = r#"${src[t.BUILD]}"#;\n`;
writeFileSync(new URL('../wasm/devcore/src/semver_re.rs', import.meta.url), out);
console.log(out.length, 'bytes');
