// Generates src/icons.gen.ts with only the Lucide icons the app uses (ISC licence).
// Any quoted PascalCase string in src/ that names a Lucide icon is included.
import { fileURLToPath } from 'node:url';
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import * as L from 'lucide-static';

const root = fileURLToPath(new URL('../src/', import.meta.url));
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (/\.ts$/.test(f) && !f.endsWith('.gen.ts')) files.push(p); } })(root);
const names = new Set(['Circle']);
for (const f of files) for (const m of readFileSync(f, 'utf8').matchAll(/'([A-Z][A-Za-z0-9]*)'/g)) if (typeof L[m[1]] === 'string') names.add(m[1]);
const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim();
const out = [...names].sort().map((n) => `  ${n}: ${JSON.stringify(inner(L[n]))},`).join('\n');
writeFileSync(join(root, 'icons.gen.ts'), `// GENERATED by scripts/gen-icons.mjs — do not edit. Icons: Lucide (ISC licence).\nexport const ICONS: Record<string, string> = {\n${out}\n};\n`);
console.log(`icons.gen.ts: ${names.size} icons`);
