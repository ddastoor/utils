// Generates the Lucide icons the app uses (ISC licence), in two parts:
//  - src/icons.gen.ts       the icons the start page can show: those named in the shell's own files — src/main.ts and every
//                           module it reaches by import, static or dynamic, except the tabs (src/tools/) — that is the
//                           categories, every tab's icon (src/registry.ts), the header and the shared controls (src/ui.ts);
//  - src/icons-tabs.gen.ts  every other icon (the tabs' own buttons), added to the same map when the first tab is opened
//                           (the registry's loaders fetch it with the tab), so the start page does not carry them.
// Any quoted PascalCase string in src/ that names a Lucide icon is included.
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname, resolve, relative, sep } from 'node:path';
import * as L from 'lucide-static';

const root = fileURLToPath(new URL('../src/', import.meta.url));
const tools = join(root, 'tools') + sep;

/** The Lucide icons a source file names ('Camera', 'ArrowUp' …). */
const namesIn = (file) => [...readFileSync(file, 'utf8').matchAll(/'([A-Z][A-Za-z0-9]*)'/g)].map((m) => m[1]).filter((n) => typeof L[n] === 'string');

/** The shell's files: src/main.ts and what it imports, statically or dynamically — but not the tabs (src/tools/). */
export function shellFiles() {
  const seen = new Set(), todo = [join(root, 'main.ts')];
  const resolveTs = (from, spec) => {
    if (!spec.startsWith('.') || spec.includes('?')) return null; // a package, or a ?url / ?worker import
    const p = resolve(dirname(from), spec);
    for (const c of [p, `${p}.ts`, join(p, 'index.ts')]) if (c.endsWith('.ts') && existsSync(c) && statSync(c).isFile()) return c;
    return null;
  };
  while (todo.length) {
    const f = todo.pop(); if (seen.has(f)) continue; seen.add(f);
    const s = readFileSync(f, 'utf8');
    for (const m of s.matchAll(/(?:^|[;\s])(?:import|export)\s+(?:[\w*{}\s,]+?\s+from\s+)?['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)/g)) {
      const dynamic = m[2] !== undefined, p = resolveTs(f, m[1] ?? m[2]);
      if (!p || p.endsWith('.gen.ts')) continue;
      if (dynamic && p.startsWith(tools)) continue; // a tab: its icons come with it
      todo.push(p);
    }
  }
  return [...seen].sort();
}

/** Which icons go where: { shell, tabs } (sorted names; 'Circle' — the stand-in for a missing icon — is the shell's). */
export function plan() {
  const files = [];
  (function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (/\.ts$/.test(f) && !f.endsWith('.gen.ts')) files.push(p); } })(root);
  const shell = new Set(['Circle']);
  for (const f of shellFiles()) for (const n of namesIn(f)) shell.add(n);
  const tabs = new Set();
  for (const f of files) for (const n of namesIn(f)) if (!shell.has(n)) tabs.add(n);
  return { shell: [...shell].sort(), tabs: [...tabs].sort() };
}

const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim();
const entries = (names) => names.map((n) => `  ${n}: ${JSON.stringify(inner(L[n]))},`).join('\n');

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { shell, tabs } = plan();
  writeFileSync(join(root, 'icons.gen.ts'), `// GENERATED by scripts/gen-icons.mjs — do not edit. Icons: Lucide (ISC licence).\n// The icons the start page can show; the tabs' own are in icons-tabs.gen.ts, added with the first tab.\nexport const ICONS: Record<string, string> = {\n${entries(shell)}\n};\n`);
  writeFileSync(join(root, 'icons-tabs.gen.ts'), `// GENERATED by scripts/gen-icons.mjs — do not edit. Icons: Lucide (ISC licence).\n// The tabs' own icons: added to the map of icons.gen.ts when the first tab is opened (src/registry.ts fetches this file\n// with every tab), so that the start page does not carry them.\nimport { ICONS } from './icons.gen';\n\nObject.assign(ICONS, {\n${entries(tabs)}\n});\n`);
  console.log(`icons.gen.ts: ${shell.length} icons for the start page; icons-tabs.gen.ts: ${tabs.length} more, with the first tab (shell files: ${shellFiles().map((f) => relative(root, f)).join(' ')})`);
}
